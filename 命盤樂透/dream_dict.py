def _normalize_num(num, max_num):
    if max_num <= 0:
        return None
    num = int(num)
    if num == 0:
        return 10 if max_num >= 10 else None
    if 1 <= num <= max_num:
        return num
    # 超過範圍時採固定折返，不丟亂數。
    folded = ((num - 1) % max_num) + 1
    return folded if 1 <= folded <= max_num else None


def _add_score(scores, numbers, weight):
    for n in numbers:
        scores[n] = scores.get(n, 0) + weight


def _resonance_numbers(numbers, max_num):
    expanded = set()
    for num in numbers:
        if num > 9:
            rev = _normalize_num(str(num)[::-1], max_num)
            if rev:
                expanded.add(rev)
            digit_sum = sum(int(d) for d in str(num))
            summed = _normalize_num(digit_sum, max_num)
            if summed:
                expanded.add(summed)
        if num < 10:
            for near in (num - 1, num + 1):
                if 1 <= near <= max_num:
                    expanded.add(near)
        tail = num % 10
        if tail:
            for candidate in range(tail, max_num + 1, 10):
                expanded.add(candidate)
    return sorted(expanded)


