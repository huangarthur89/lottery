    """回傳夢境字典、夢境密碼與逼牌延伸的可回溯解析結果。"""
    text = (user_input or "").lower()
    base_numbers = set()
    code_numbers = set()
    explicit_numbers = set()
    keywords = []
    matched_descs = []
    code_hits = []
    scores = {}

    for kw_tuple, data in dream_database.items():
        nums = [_normalize_num(n, max_num) for n in data.get("nums", [])]
        nums = sorted({n for n in nums if n})
        matched_kws = [k for k in kw_tuple if k and k.lower() in text]
        if matched_kws and nums:
            base_numbers.update(nums)
            _add_score(scores, nums, 100)
            for k in matched_kws:
                if k not in keywords:
                    keywords.append(k)
            desc_text = f"**{', '.join(matched_kws)}**：{data.get('desc', '')}"
            if desc_text not in matched_descs:
                matched_descs.append(desc_text)

    import re
    raw_numbers = re.findall(r'\d+', text)
    explicit_hit_nums = []
    for raw in raw_numbers:
        # 對 3 位以上數字同時取整數折返與末兩位，處理門牌/車牌/金額。
        candidates = [int(raw)]
        if len(raw) >= 2:
            candidates.append(int(raw[-2:]))
        for cand in candidates:
            n = _normalize_num(cand, max_num)
            if n:
                explicit_numbers.add(n)
                explicit_hit_nums.append(n)
    if explicit_hit_nums:
        nums = sorted(set(explicit_hit_nums))
        code_numbers.update(nums)
        _add_score(scores, nums, 140)
        code_hits.append({"label": "明示數字", "nums": nums, "reason": "夢裡直接出現的數字、門牌、車號或金額。"})

    chinese_hit_nums = []
    for char, value in CHINESE_NUMERAL_MAP.items():
        if char in text:
            n = _normalize_num(value, max_num)
            if n:
                chinese_hit_nums.append(n)
    if chinese_hit_nums:
        nums = sorted(set(chinese_hit_nums))
        code_numbers.update(nums)
        _add_score(scores, nums, 110)
        code_hits.append({"label": "中文數字", "nums": nums, "reason": "夢境文字中含中文數字。"})

    resonance_numbers = set()
    if include_resonance:
        seed_numbers = sorted(base_numbers | code_numbers | explicit_numbers)
        resonance_numbers = set(_resonance_numbers(seed_numbers, max_num)) - set(seed_numbers)
        if resonance_numbers:
            nums = sorted(resonance_numbers)
            _add_score(scores, nums, 35)
            code_hits.append({"label": "鏡像/合數/尾數延伸", "nums": nums[:18], "reason": "由命中的夢碼固定推導：倒牌、數字合數、鄰號與同尾數。"})

    all_numbers = sorted(base_numbers | code_numbers | explicit_numbers | resonance_numbers)
    ranked_numbers = sorted(all_numbers, key=lambda n: (-scores.get(n, 0), n))
    return {
        "numbers": ranked_numbers,
        "base_numbers": sorted(base_numbers),
        "code_numbers": sorted(code_numbers | explicit_numbers),
        "resonance_numbers": sorted(resonance_numbers),
        "keywords": keywords,
        "matched_descs": matched_descs,
        "code_hits": code_hits,
        "scores": scores,
    }
